// 👕 (02/11/2026) מידות באותיות — בברקוד יש ספרה אחת למידה; הסדר שקבע המנהל: XS=0 S=1 M=2 L=3 XL=4 XXL=5 3XL=6 4XL=7.
// products.szLetters = הזמנה שהמידות שלה באותיות. הנתונים (כמויות, ברקודים, משימות) נשארים ספרות — רק התצוגה מתורגמת.
const SZ_LET=['XS','S','M','L','XL','XXL','3XL','4XL'];
function szLbl(s,p){const z=String(s??'');return p?.szLetters&&/^[0-7]$/.test(z)?SZ_LET[+z]:z;}
const szLblT=(cust,prod,s)=>szLbl(s,findProd(cust,prod));
// קלט: אות מוכרת ⇒ הספרה שלה (2XL=XXL, XXXL=3XL); כל דבר אחר נשאר כמו שהוקלד
function szDigit(v){const r=String(v??'').trim(),u=r.toUpperCase().replace(/\s/g,'').replace(/^2XL$/,'XXL').replace(/^XXXL$/,'3XL').replace(/^XXXXL$/,'4XL'),i=SZ_LET.indexOf(u);return i>=0?String(i):r;}
function findProd(cust,prod){
  let best=null,mx=-1;
  for(const p of (S.products||[])){
    if(p.cust!==cust||p.prod!==prod)continue;
    const c=+p.createdAt||parseInt(String(p.id).replace(/\D/g,''))||0;
    if(c>mx){mx=c;best=p;}
  }
  return best;
}

